-- ============================================================
-- StudentsRegister — MySQL initialisation script
-- Server + credentials are HARDCODED (lab setup, same as .env):
--   host: 100.105.204.3   db: student_db
--   app user: student_user / <set-at-install>
--
-- Run as root (or any admin user):
--   mysql -h 100.105.204.3 -u root -p < db/init.sql
--
-- Safe to re-run (IF NOT EXISTS everywhere).
-- NOTE: the app (spring.jpa.hibernate.ddl-auto=update) also creates/
-- updates these tables automatically — this script lets a DBA build
-- the exact same schema by hand.
-- ============================================================

CREATE DATABASE IF NOT EXISTS student_db
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'student_user'@'%' IDENTIFIED BY 'CHANGE_ME_BEFORE_RUNNING';
GRANT ALL PRIVILEGES ON student_db.* TO 'student_user'@'%';
FLUSH PRIVILEGES;

USE student_db;

-- ------------------------------------------------ students (roster)
CREATE TABLE IF NOT EXISTS students (
  id            BIGINT AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(255) NOT NULL,
  email         VARCHAR(255) NOT NULL UNIQUE,
  phone         VARCHAR(255) NOT NULL,
  course        VARCHAR(255) NOT NULL,
  status        VARCHAR(255) NOT NULL DEFAULT 'active',
  enrolled_date DATETIME(6),
  created_at    DATETIME(6)
) ENGINE = InnoDB;

-- ------------------------------------------------ login accounts
CREATE TABLE IF NOT EXISTS app_users (
  id            BIGINT AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name     VARCHAR(255) NOT NULL,
  role          VARCHAR(255) NOT NULL DEFAULT 'STUDENT',
  student_id    BIGINT NULL,
  active        BIT(1) NOT NULL DEFAULT b'1',
  created_at    DATETIME(6),
  last_login_at DATETIME(6)
) ENGINE = InnoDB;

-- ------------------------------------------------ daily topic log
CREATE TABLE IF NOT EXISTS topic_entries (
  id          BIGINT AUTO_INCREMENT PRIMARY KEY,
  student_id  BIGINT NOT NULL,
  entry_date  DATE NOT NULL,
  topic       VARCHAR(255) NOT NULL,
  description TEXT,
  hours_spent DOUBLE NULL,
  signed_at   DATETIME(6) NOT NULL,
  INDEX idx_topic_student (student_id),
  INDEX idx_topic_date (entry_date)
) ENGINE = InnoDB;

-- ------------------------------------------------ student projects
CREATE TABLE IF NOT EXISTS projects (
  id             BIGINT AUTO_INCREMENT PRIMARY KEY,
  student_id     BIGINT NOT NULL,
  title          VARCHAR(255) NOT NULL,
  description    TEXT,
  tech_stack     VARCHAR(255),
  repo_url       VARCHAR(255),
  status         VARCHAR(255) NOT NULL DEFAULT 'PLANNED',
  started_date   DATE NULL,
  completed_date DATE NULL,
  created_at     DATETIME(6),
  INDEX idx_project_student (student_id)
) ENGINE = InnoDB;

